# -*- coding: utf-8 -*-
"""Container capacity audit (user, 2026-11-14: "Pallet of Green Military Cases" builds with 25
instead of 90). For every container buildable in our WE submods (work copy), compare the
definition's container (type, capacity) with the container the TILE itself declares
(container / ContainerCapacity). KBW's Properties.lua calls setCapacity(stage.container.capacity)
on the built object, so the definition wins when building; placing the same tile any other way
(debug / moveable place) gives the tile's value. Rows where they differ are listed.

Writes zomboid/communitytilepack/CONTAINER_CAPACITY_AUDIT.md (+ .csv)."""
import collections
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kbw_tilepatch as k                    # noqa: E402

WORK = r"c:\Users\josep\Kiro\zomboid\WE_submods\work"
OUT_MD = r"c:\Users\josep\Kiro\zomboid\communitytilepack\CONTAINER_CAPACITY_AUDIT.md"
OUT_CSV = OUT_MD[:-3] + ".csv"


def tile_props():
    """sprite name -> property dict: vanilla, Community pack, TikiTown pack, then our own tiles
    (our .patch.tiles merge on top of the pack tile, like the game does)."""
    props = {}

    def add(path, merge=False):
        _v, ts, _o = k._parse(open(path, "rb").read())
        for n, t in ts.items():
            for i, p in enumerate(t[6]):
                name = "%s_%d" % (n.decode(), i)
                d = {a.decode(): b.decode("latin-1") for a, b in p}
                if merge:
                    if d:
                        props.setdefault(name, {}).update(d)
                else:
                    props[name] = d
    add(k._VANILLA_TILES)
    for p in glob.glob(os.path.join(os.path.dirname(k._COMMUNITY_TILES), "*.tiles")):
        add(p)
    add(k._TIKITOWN_TILES)
    for p in glob.glob(os.path.join(WORK, "*", "42", "media", "*.tiles")):
        add(p, merge=p.endswith(".patch.tiles"))
    return props


def main():
    props = tile_props()
    rows = []
    for f in sorted(glob.glob(os.path.join(WORK, "*", "42", "media", "KnoxBuildworks", "definitions", "*.json"))):
        sub = "C" if "Community" in f else "T"
        d = json.load(open(f, encoding="utf-8-sig"))
        for b in d.get("buildables", []):
            for st in b.get("stages") or []:
                c = st.get("container")
                if not c:
                    continue
                sprites = [s for face in ((st.get("geometry") or {}).get("faces") or {}).values()
                           for L in face.get("layers", []) for r in L.get("rows", []) for s in r if s]
                tiles = [(s, props.get(s, {})) for s in dict.fromkeys(sprites)]
                tc = [(s, p.get("container"), p.get("ContainerCapacity")) for s, p in tiles if p.get("container")]
                tcaps = sorted({int(x[2]) for x in tc if x[2] and x[2].isdigit()})
                ttypes = sorted({x[1] for x in tc})
                dcap, dtype = c.get("capacity"), c.get("type")
                if not tc:
                    status = "tile has no container"
                elif dcap is None:
                    status = "definition has no capacity"
                elif tcaps and dcap < max(tcaps):
                    status = "definition LOWER"
                elif tcaps and dcap > max(tcaps):
                    status = "definition higher"
                else:
                    status = "same"
                rows.append({"file": sub + os.path.basename(f).split("_", 1)[0], "id": b["id"],
                             "name": b.get("displayName", ""), "stage": st.get("id", ""),
                             "def_type": dtype, "def_cap": dcap, "tile_types": "/".join(ttypes),
                             "tile_caps": "/".join(map(str, tcaps)), "status": status,
                             "reinforced": b["id"].endswith(".reinforced") or "Reinforced" in b.get("displayName", "")})
    with open(OUT_CSV, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    cnt = collections.Counter(r["status"] for r in rows)
    L = ["# Container capacity audit (generated)", "",
         "Generated by `pz_craft_loops/container_capacity_audit.py` from the WE work copy. Definition = "
         "`stage.container` (what a KBW build gets: Properties.lua sets the capacity on the built object). "
         "Tile = the sprite's own `container` / `ContainerCapacity` (what debug / moveable placement gets).", "",
         "| Status | stages |", "|---|---:|"] + ["| %s | %d |" % kv for kv in cnt.most_common()] + [""]
    for status in ("definition LOWER", "definition higher", "definition has no capacity"):
        sel = [r for r in rows if r["status"] == status and not r["reinforced"]]
        if not sel:
            continue
        L += ["## %s (%d, reinforced versions not listed)" % (status, len(sel)), "",
              "| File | Name | definition | tile | id |", "|---|---|---|---|---|"]
        for r in sorted(sel, key=lambda r: (r["file"], r["name"])):
            L.append("| %s | %s | %s %s | %s %s | `%s` |" % (r["file"], r["name"], r["def_type"], r["def_cap"],
                                                         r["tile_types"], r["tile_caps"], r["id"]))
        L.append("")
    open(OUT_MD, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(dict(cnt), "->", OUT_MD)


if __name__ == "__main__":
    main()
