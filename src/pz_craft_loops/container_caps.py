# -*- coding: utf-8 -*-
"""Stage property `kbwcbContainerCapacity` for Knox Buildworks (2026-11-02, EXPERIMENTAL).

KBW's own `container` property sets only the object's FIRST container (part:getContainer()).
Fridges have two (fridge + freezer, both created from tile properties). KBW exposes a public
stage-property registry (Definitions/Properties.lua: "Third-party mods register their own"), so
we register a property that sets capacity per container TYPE:

    "kbwcbContainerCapacity": {"fridge": 100, "freezer": 100}

applyToObject runs server-side for every built part after its containers exist (prop path:
placeMoveableInternal creates them from the tile's container / Freezer properties first).
The build-menu tooltip still shows the tile's numbers (KBW reads tile properties).

Lua is Kahlua-safe: no next(), goto, //, bit ops or debug.
"""
import os

LUA_NAME = "KBWCommunity_StageProperties.lua"
PROPERTY = "kbwcbContainerCapacity"
# Second property (2026-11-02): "kbwcbContainerTypes": {"fridge": "freezer"} retypes containers
# (ItemContainer:setType) for the freezer-only refrigerators. EXPERIMENTAL: whether the type
# survives a save/reload is not verified yet. (The earlier kbwcbReplacePrevious property for
# 2-tile shells was removed with the 2-tile two-stage builds.)

_LUA = r'''-- AUTO-GENERATED by pz_craft_loops/container_caps.py -- do not edit by hand.
-- Stage property "kbwcbContainerCapacity" for Knox Buildworks: sets the capacity of each of a
-- built object's containers by container type, e.g. { fridge = 100, freezer = 100 }.
-- KBW's own "container" property only sets the first container; fridges have two.
-- Registered through KBW's public stage-property registry (Definitions/Properties.lua).
local ok, Properties = pcall(require, "KnoxBuildworks/Definitions/Properties")
if not ok or type(Properties) ~= "table" or not Properties.register then
    print("[KBWCommunity] ContainerCapacities: Knox Buildworks Properties not found; not registered")
    return
end

local MAX_CAPACITY = 100   -- the game's per-container limit

local function containerAt(part, index)
    local okGet, container = pcall(function() return part:getContainerByIndex(index) end)
    if okGet then return container end
    return nil
end

local function containerCount(part)
    local okCount, count = pcall(function() return part:getContainerCount() end)
    if okCount and type(count) == "number" then return count end
    return 0
end

Properties.register("kbwcbContainerCapacity", {
    normalize = function(value, stage, definition, addError)
        if type(value) ~= "table" then
            addError("must map container types to capacities, e.g. { fridge = 100, freezer = 100 }")
            return value
        end
        for containerType, capacity in pairs(value) do
            if type(containerType) ~= "string" or type(capacity) ~= "number" then
                addError("each entry must be containerType = number")
            elseif capacity < 1 or capacity > MAX_CAPACITY then
                addError("capacity for '" .. containerType .. "' must be 1-" .. tostring(MAX_CAPACITY))
            end
        end
        return value
    end,
    applyToObject = function(part, buildObj, stage, context)
        if not part or (context and context.isFloor) then return end
        local wanted = stage.kbwcbContainerCapacity
        if type(wanted) ~= "table" then return end
        local done = {}
        local count = containerCount(part)
        for index = 0, count - 1 do
            local container = containerAt(part, index)
            local containerType = container and container:getType() or nil
            local capacity = containerType and wanted[containerType] or nil
            if capacity then
                container:setCapacity(capacity)
                done[#done + 1] = containerType .. "=" .. tostring(capacity)
            end
        end
        print("[KBWCommunity] ContainerCapacities " .. tostring(buildObj and buildObj.buildableId)
            .. ": " .. tostring(count) .. " container(s), set " .. table.concat(done, ", "))
    end,
})
print("[KBWCommunity] ContainerCapacities: registered stage property kbwcbContainerCapacity")

-- "kbwcbContainerTypes": { fridge = "freezer" } -- retype a built object's containers by their
-- current type. Used by the freezer-only refrigerators: the tile's main "fridge" compartment
-- becomes a second "freezer". Pair it with kbwcbContainerCapacity giving both types the same
-- capacity, so the result doesn't depend on which property runs first.
Properties.register("kbwcbContainerTypes", {
    normalize = function(value, stage, definition, addError)
        if type(value) ~= "table" then
            addError("must map container types to new types, e.g. { fridge = \"freezer\" }")
            return value
        end
        for fromType, toType in pairs(value) do
            if type(fromType) ~= "string" or type(toType) ~= "string" or toType == "" then
                addError("each entry must be containerType = \"newType\"")
            end
        end
        return value
    end,
    applyToObject = function(part, buildObj, stage, context)
        if not part or (context and context.isFloor) then return end
        local wanted = stage.kbwcbContainerTypes
        if type(wanted) ~= "table" then return end
        local done = {}
        local count = containerCount(part)
        for index = 0, count - 1 do
            local container = containerAt(part, index)
            local fromType = container and container:getType() or nil
            local toType = fromType and wanted[fromType] or nil
            if toType then
                local okSet = pcall(function() container:setType(toType) end)
                done[#done + 1] = fromType .. "->" .. toType .. (okSet and "" or " (FAILED)")
            end
        end
        print("[KBWCommunity] ContainerTypes " .. tostring(buildObj and buildObj.buildableId)
            .. ": " .. tostring(count) .. " container(s), " .. table.concat(done, ", "))
    end,
})
print("[KBWCommunity] StageProperties: registered stage property kbwcbContainerTypes")
'''


# ---- build-menu text -------------------------------------------------------------------------
# KBW's BuildableInfo (client) shows container sizes from the TILE's properties (ContainerCapacity /
# FreezerCapacity win over stage.container.capacity) and knows nothing of our properties, so tiered
# fridges / freezers / ice machines all showed the vanilla numbers. This client file wraps
# BuildableInfo.containerTiles (every capacity line goes through that table field) and applies
# kbwcbContainerCapacity, kbwcbContainerTypes and stage container.capacity (first container, the
# same one KBW's own property sets) to the text only.
INFO_LUA_NAME = "KBWCommunity_StageInfo.lua"
_INFO_LUA = r'''-- AUTO-GENERATED by pz_craft_loops/container_caps.py -- do not edit by hand.
-- Build-menu capacity text for our stage properties (see KBWCommunity_StageProperties.lua).
-- KBW reads tile properties for the "Tile 1 - Fridge: 40 + Freezer: 20" line; this applies the
-- capacities / container types the built object will really get. Display only.
local function containerName(containerType)
    local text = getTextOrNull and getTextOrNull("IGUI_ContainerTitle_" .. tostring(containerType)) or nil
    return text or tostring(containerType)
end

local function install()
    local ok, BuildableInfo = pcall(require, "KnoxBuildworks/UI/BuildableInfo")
    if not ok or type(BuildableInfo) ~= "table" or type(BuildableInfo.containerTiles) ~= "function" then
        print("[KBWCommunity] StageInfo: Knox Buildworks BuildableInfo not found; capacity text unchanged")
        return false
    end
    if BuildableInfo._kbwcbStageInfo then return true end
    BuildableInfo._kbwcbStageInfo = true
    local original = BuildableInfo.containerTiles
    BuildableInfo.containerTiles = function(stage)
        local tiles = original(stage)
        if type(stage) ~= "table" or type(tiles) ~= "table" then return tiles end
        local caps = stage.kbwcbContainerCapacity
        local types = stage.kbwcbContainerTypes
        local first = type(stage.container) == "table" and tonumber(stage.container.capacity) or nil
        if type(caps) ~= "table" and type(types) ~= "table" and not first then return tiles end
        for tileIndex = 1, #tiles do
            local list = tiles[tileIndex].containers or {}
            for index = 1, #list do
                local entry = list[index]
                local fromType = entry.type
                if index == 1 and first then entry.capacity = first end
                if type(caps) == "table" and caps[fromType] then entry.capacity = caps[fromType] end
                if type(types) == "table" and types[fromType] then
                    entry.type = types[fromType]
                    entry.kind = types[fromType]
                    entry.name = containerName(types[fromType])
                end
            end
        end
        return tiles
    end
    print("[KBWCommunity] StageInfo: build-menu capacity text installed")
    return true
end

if not install() then Events.OnGameStart.Add(install) end

-- Inventory tooltip for picked-up builds (KBWCommunity_Pickup.lua stores modData.kbwcbStorage on
-- the moveable item). The item's list name can't be changed (Moveable.getName ignores the item
-- name), so the tooltip gets a box under it: our build's name + its storage.
local function storageLines(record)
    local lines = {}
    if type(record.name) == "string" and record.name ~= "" then
        lines[#lines + 1] = { text = record.name, r = 1, g = 0.85, b = 0.35 }
    end
    local parts = {}
    local list = record.containers
    if type(list) == "table" then
        for index = 1, #list do
            local entry = list[index]
            if type(entry) == "table" and entry.type and entry.capacity then
                parts[#parts + 1] = containerName(entry.type) .. ": " .. tostring(entry.capacity)
            end
        end
    end
    if #parts > 0 then
        lines[#lines + 1] = { text = table.concat(parts, " + "), r = 0.86, g = 0.78, b = 0.45 }
    end
    return lines
end

local function installTooltip()
    if type(ISToolTipInv) ~= "table" or type(ISToolTipInv.render) ~= "function" then return false end
    if ISToolTipInv._kbwcbStorageTip then return true end
    ISToolTipInv._kbwcbStorageTip = true
    local originalRender = ISToolTipInv.render
    ISToolTipInv.render = function(self)
        originalRender(self)
        if ISContextMenu and ISContextMenu.instance and ISContextMenu.instance.visibleCheck then return end
        local item = self.item
        if not item then return end
        local record = nil
        pcall(function()
            if item:hasModData() then record = item:getModData().kbwcbStorage end
        end)
        if type(record) ~= "table" then return end
        local lines = storageLines(record)
        if #lines == 0 then return end
        local tm = getTextManager()
        local lineHeight = tm:getFontHeight(UIFont.Small)
        local width = self.width
        for index = 1, #lines do
            width = math.max(width, tm:MeasureStringX(UIFont.Small, lines[index].text) + 16)
        end
        local height = #lines * lineHeight + 8
        local y = self.height
        if self:getAbsoluteY() + y + height > getCore():getScreenHeight() then y = -height end
        self:drawRect(0, y, width, height, self.backgroundColor.a, self.backgroundColor.r,
            self.backgroundColor.g, self.backgroundColor.b)
        self:drawRectBorder(0, y, width, height, self.borderColor.a, self.borderColor.r,
            self.borderColor.g, self.borderColor.b)
        for index = 1, #lines do
            local line = lines[index]
            self:drawText(line.text, 8, y + 4 + (index - 1) * lineHeight, line.r, line.g, line.b, 1, UIFont.Small)
        end
    end
    print("[KBWCommunity] StageInfo: picked-up build tooltip installed")
    return true
end

if not installTooltip() then Events.OnGameStart.Add(installTooltip) end
'''


# ---- pick up / place keeps our version -------------------------------------------------------
# Vanilla pick-up turns the object into a plain moveable item that only remembers its sprite;
# placing it rebuilds the containers from the TILE (vanilla capacities / types). This shared file
# wraps ISMoveableSpriteProps:
#   pickUpMoveableInternal -> while it runs, the item vanilla creates (instanceItem) gets
#     modData.kbwcbStorage = { buildableId, name, containers = { {type, capacity}, ... } } before
#     vanilla adds / sends it. (Renaming is impossible: Moveable.getName builds the name from the
#     tile; the inventory tooltip shows our name + storage instead, KBWCommunity_StageInfo.lua.)
#   placeMoveableInternal  -> if the placed item carries kbwcbStorage, re-apply container types and
#     capacities to the new object and keep the record on it (so the next pick-up keeps the name).
# "Ours" = KBW buildableId starting with one of OUR_PREFIXES, or an object that already carries a
# record. Multi-tile ForceSingleItem pieces (one item for the whole grid) are not covered.
PICKUP_LUA_NAME = "KBWCommunity_Pickup.lua"
OUR_PREFIXES = ("community.", "tikitown.", "worldessentials.tikitown.", "kbwcb.")
_PICKUP_LUA = r'''-- AUTO-GENERATED by pz_craft_loops/container_caps.py -- do not edit by hand.
-- Picking up one of our builds keeps our version: container capacities / types travel on the
-- moveable item (modData.kbwcbStorage) and come back when it is placed; the item shows our name.
local PREFIXES = { %(prefixes)s }

local function isOurs(id)
    if type(id) ~= "string" then return false end
    for index = 1, #PREFIXES do
        if string.find(id, PREFIXES[index], 1, true) == 1 then return true end
    end
    return false
end

local function displayNameFor(id)
    local okR, Registry = pcall(require, "KnoxBuildworks/Definitions/Registry")
    if not okR or type(Registry) ~= "table" or not Registry.get then return nil end
    local okD, definition = pcall(function() return Registry:get(id) end)
    if not okD or type(definition) ~= "table" then return nil end
    local okI, I18n = pcall(require, "KnoxBuildworks/I18n")
    if okI and type(I18n) == "table" and I18n.definitionName then
        local okN, name = pcall(I18n.definitionName, definition)
        if okN and type(name) == "string" and name ~= "" and name ~= "?" then return name end
    end
    return definition.displayName
end

local function containerAt(object, index)
    local okGet, container = pcall(function() return object:getContainerByIndex(index) end)
    if okGet then return container end
    return nil
end

local function containerCount(object)
    local okCount, count = pcall(function() return object:getContainerCount() end)
    if okCount and type(count) == "number" then return count end
    return 0
end

-- record for one of our objects, or nil
local function recordFor(object)
    if not object then return nil end
    local okData, data = pcall(function() return object:getModData() end)
    if not okData or type(data) ~= "table" then return nil end
    local kbw = data.KBW
    local prior = data.kbwcbStorage
    local id = type(kbw) == "table" and kbw.buildableId or nil
    if not isOurs(id) then
        if type(prior) ~= "table" then return nil end
        id = prior.buildableId
    end
    local record = { buildableId = id, name = displayNameFor(id) }
    if not record.name and type(prior) == "table" then record.name = prior.name end
    local containers = {}
    for index = 0, containerCount(object) - 1 do
        local container = containerAt(object, index)
        if container then
            local okCap, capacity = pcall(function() return container:getCapacity() end)
            containers[#containers + 1] = { type = container:getType(), capacity = okCap and capacity or nil }
        end
    end
    record.containers = containers
    return record
end

local function applyRecord(object, record)
    local list = record.containers
    local done = {}
    if type(list) == "table" then
        for index = 1, #list do
            local want = list[index]
            local container = containerAt(object, index - 1)
            if container and type(want) == "table" then
                if type(want.type) == "string" and container:getType() ~= want.type then
                    pcall(function() container:setType(want.type) end)
                end
                if type(want.capacity) == "number" then
                    pcall(function() container:setCapacity(want.capacity) end)
                end
                done[#done + 1] = tostring(container:getType()) .. "=" .. tostring(want.capacity)
            end
        end
    end
    local okData, data = pcall(function() return object:getModData() end)
    if okData and type(data) == "table" then data.kbwcbStorage = record end
    pcall(function() object:transmitModData() end)
    print("[KBWCommunity] Pickup: placed " .. tostring(record.buildableId) .. " restored " .. table.concat(done, ", "))
end

local function install()
    if type(ISMoveableSpriteProps) ~= "table" then pcall(require, "Moveables/ISMoveableSpriteProps") end
    local P = ISMoveableSpriteProps
    if type(P) ~= "table" or type(P.pickUpMoveableInternal) ~= "function"
        or type(P.placeMoveableInternal) ~= "function" or type(P.instanceItem) ~= "function" then
        return false
    end
    if P._kbwcbPickup then return true end
    P._kbwcbPickup = true

    local originalInstance = P.instanceItem
    P.instanceItem = function(self, spriteName)
        local item = originalInstance(self, spriteName)
        local pending = self._kbwcbPending
        if item and pending then
            self._kbwcbPending = nil
            -- (the list name can't be changed: Moveable.getName ignores the item name; the
            -- inventory tooltip shows record.name instead, see KBWCommunity_StageInfo.lua)
            pcall(function() item:getModData().kbwcbStorage = pending end)
        end
        return item
    end

    local originalPickUp = P.pickUpMoveableInternal
    P.pickUpMoveableInternal = function(self, character, square, object, sprInstance, spriteName, createItem, rotating)
        local okRecord, record = pcall(recordFor, (not sprInstance) and object or nil)
        self._kbwcbPending = okRecord and record or nil
        local a, b = originalPickUp(self, character, square, object, sprInstance, spriteName, createItem, rotating)
        self._kbwcbPending = nil
        return a, b
    end

    local originalPlace = P.placeMoveableInternal
    P.placeMoveableInternal = function(self, character, square, item, spriteName)
        local record = nil
        pcall(function()
            if item and item:hasModData() then record = item:getModData().kbwcbStorage end
        end)
        local object, b = originalPlace(self, character, square, item, spriteName)
        if object and type(record) == "table" then
            local okApply, err = pcall(applyRecord, object, record)
            if not okApply then print("[KBWCommunity] Pickup: restore failed: " .. tostring(err)) end
        end
        return object, b
    end
    print("[KBWCommunity] Pickup: pick up / place keeps our builds' storage and name")
    return true
end

if not install() then
    Events.OnGameStart.Add(install)
    if Events.OnServerStarted then Events.OnServerStarted.Add(install) end
end
''' % {"prefixes": ", ".join('"%s"' % p for p in OUR_PREFIXES)}


def write_pickup_lua(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write(_PICKUP_LUA)
    for bad in ("next(", "goto ", "//", "debug."):
        if bad in _PICKUP_LUA.replace("-- AUTO-GENERATED", ""):
            raise RuntimeError("Kahlua-unsafe construct in %s: %s" % (PICKUP_LUA_NAME, bad))


def previous_stage_names(buildables):
    """IG_UI entries for KBW's "Build first: <name>" line. KBW looks up
    IGUI_KBW_Vanilla_<previousStage id> and falls back to the raw id."""
    by_id = {b.get("id"): b for b in buildables}
    out = {}
    for b in buildables:
        for st in b.get("stages") or []:
            prev = st.get("previousStage")
            for pid in ([prev] if isinstance(prev, str) else (prev or [])):
                target = by_id.get(pid)
                if target and target.get("displayName"):
                    out["IGUI_KBW_Vanilla_" + pid] = target["displayName"]
    return out


