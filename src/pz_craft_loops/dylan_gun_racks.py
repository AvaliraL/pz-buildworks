# -*- coding: utf-8 -*-
"""Generate 66_community_dylan_gun_racks.json (user, 2026-08-28; second attempt): the two pegboard
gun racks of Dylan's DarthGunStore (Community pack). Each rack is 2 tiles wide with 2 facings:
  rack 1: N = 8 + 9 (along the north wall), W = 11 over 10 (along the west wall)
  rack 2: N = 12 + 13,                      W = 15 over 14
(tile order S, W, S, W per the user; joins composited from the art). Each tile is its own
metal_shelves container (10, as the pack), and shows the pack's gun overlay once it holds items.
Built on our copies (kbw_tilepatch.GUN_RACKS, KBWCommunityIceShell_160..175): the first attempt was
dropped for a "placement bug" because the pack tiles are WallOverlay moveables (WE attaches them as
bare wall sprites, no object and no storage). Names from the overlay art.
Cost: the Dirkies Metal Wall Shelves' (kbwve.extended.metal, MetalWelding 4, Projects in Metal).
Reinforced versions by the default rule (tag "reinforce": 100 per tile). NOT yet tested in game.
"""
import copy
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kbw_tilepatch import GUN_SHEET, decor_copy_name  # noqa: E402

DELIV = r"c:\Users\josep\Kiro\zomboid\communitytilepack\deliverables"
OUT = os.path.join(DELIV, "66_community_dylan_gun_racks.json")
COST_FROM = ("40_community_dirkies_containers.json",
             "community.dirkies.containers.location_community_medical_ddd_01_12")   # Metal Wall Shelves
GROUP = {"id": "community.dylan.gun_racks", "name": "Gun Racks",
         "translationKey": "IGUI_community_dylan_gun_racks_group"}
RACKS = [  # (slug, name, N row west->east, W column north->south)
    ("rifles_shotguns", "Pegboard Gun Rack (Rifles and Shotguns)", (8, 9), (11, 10)),
    ("rifles_pistols", "Pegboard Gun Rack (Rifles and Pistols)", (12, 13), (15, 14)),
]


def _c(i):
    return decor_copy_name(i, GUN_SHEET)


def _cost():
    d = json.load(open(os.path.join(DELIV, COST_FROM[0]), encoding="utf-8"))
    b = next(x for x in d["buildables"] if x["id"] == COST_FROM[1])
    return copy.deepcopy(b["stages"][0]["requirements"]), copy.deepcopy(b["construction"])


def build_document():
    out = []
    for level, (slug, name, north, west) in enumerate(RACKS, 1):
        req, con = _cost()
        bid = "community.dylan.gun_rack_%s" % slug
        out.append({
            "id": bid,
            "allowSpriteReuse": True,
            "translationKey": "IGUI_" + bid.replace(".", "_"),
            "displayName": name,
            "category": "Containers",
            "subcategory": "Gun Racks",
            "material": "Metal",
            "materialTags": ["Metal"],
            "iconSprite": _c(north[0]),
            "placement": {"kind": "object", "requiresFloor": True, "needToBeAgainstWall": True},
            "tags": ["community-tilepack", "dylan", "container", "gun-rack", "reinforce"],
            "group": dict(GROUP, level=level),
            "construction": con,
            "stages": [{
                "id": "built",
                "geometry": {"faces": {
                    "N": {"layers": [{"rows": [[_c(north[0]), _c(north[1])]]}]},
                    "W": {"layers": [{"rows": [[_c(west[0])], [_c(west[1])]]}]},
                }},
                "requirements": req,
                "object": {"isThumpable": True, "dismantable": True},
                "container": {"type": "metal_shelves", "capacity": 10},
            }],
        })
    return {
        "schemaVersion": 1,
        "category": "Containers",
        "source": ("Dylan DarthGunStore (Community pack) pegboard gun racks on our wall-object copies "
                   "(KBWCommunityIceShell_160..175, fill overlays included). Generated by "
                   "pz_craft_loops/dylan_gun_racks.py."),
        "buildables": out,
    }


def main():
    doc = build_document()
    ids = [b["id"] for b in doc["buildables"]]
    assert len(ids) == len(set(ids))
    json.dump(doc, open(OUT, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("wrote %s (%d buildables)" % (OUT, len(ids)))


if __name__ == "__main__":
    main()
