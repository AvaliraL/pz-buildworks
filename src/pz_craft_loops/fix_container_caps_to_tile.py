"""Container capacity fix (user, 2026-11-14). Bug report: "Pallet of Green Military Cases" built
with 25 instead of 90. Our addon transpiler gave every addon-"Crates" piece the generic smallcrate
25, ignoring the tile's own container; KBW applies the definition's capacity to the built object,
so builds came out at 25 while debug / moveable placement (tile values) gave 90.

container_capacity_audit.py found 16 buildables whose definition is LOWER than the tile. Per the
user, all 16 now take the tile's own container type and ContainerCapacity. Edits the deliverables
in place (they are the source the builders read); idempotent. Reinforced siblings are generated by
counter_variants at build time and keep their own 100."""
import json
import os

DELIV = r"c:\Users\josep\Kiro\zomboid\communitytilepack\deliverables"
# id -> (tile container type, tile ContainerCapacity), from CONTAINER_CAPACITY_AUDIT.md
FIX = {
    "40_community_dirkies_containers.json": {
        "community.dirkies.containers.furniture_storage_ddd_01_7": ("StackedAmmoPallet", 90),   # green pallet
        "community.dirkies.containers.furniture_storage_ddd_01_8": ("StackedAmmoPallet", 90),   # white pallet
        "community.dirkies.containers.furniture_storage_ddd_01_4": ("locker", 30),              # green case
        "community.dirkies.containers.furniture_storage_ddd_01_9": ("locker", 30),              # white case
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_32": ("wardrobe", 25),
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_33": ("wardrobe", 25),
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_34": ("wardrobe", 25),
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_80": ("wardrobe", 25),
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_81": ("wardrobe", 25),
        "community.dirkies.containers.edit_ddd_RUS_furniture_storage_03_82": ("wardrobe", 25),
        "community.dirkies.containers.industry_dirkea_ddd_01_15": ("shelves", 80),
        "community.dirkies.containers.furniture_storage_ddd_01_34": ("shelves", 40),
    },
    "41_community_dylan_containers.json": {
        "community.dylan.containers.Bookies_Store_13": ("shelves", 40),
        "community.dylan.containers.Bookies_Store_45": ("shelves", 40),
        "community.dylan.containers.DylansRandomFurniture01_10": ("StandingToolbox", 75),
    },
    "42_community_tk_containers.json": {
        "community.tk.containers.industry_tk_02_32": ("crate", 30),
    },
}


def main():
    changed = 0
    for fn, fixes in FIX.items():
        p = os.path.join(DELIV, fn)
        raw = open(p, encoding="utf-8").read()
        doc = json.loads(raw)
        seen = set()
        for b in doc["buildables"]:
            if b["id"] not in fixes:
                continue
            seen.add(b["id"])
            ctype, cap = fixes[b["id"]]
            for st in b.get("stages") or []:
                c = st.get("container")
                if c is not None and (c.get("type"), c.get("capacity")) != (ctype, cap):
                    c["type"], c["capacity"] = ctype, cap
                    changed += 1
        missing = set(fixes) - seen
        if missing:
            raise RuntimeError("%s: ids not found %s" % (fn, sorted(missing)))
        indent = 1 if raw.startswith("{\n \"") else 2
        json.dump(doc, open(p, "w", encoding="utf-8"), indent=indent, ensure_ascii=False)
    print("stages changed:", changed)


if __name__ == "__main__":
    main()
