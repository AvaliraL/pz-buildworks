# -*- coding: utf-8 -*-
"""Ice from our ice machines (user, 2026-11-16): right-click a Commercial / Large / Industrial Ice
Machine built with Knox Buildworks -> "Make Ice" gives Sapph's Cooking ice cubes
(SapphCooking.IceCubes, 2 per use, like Sapph's own "Make Ice Cubes" recipe) with Sapph's
"IceBreaking" sound.

Guard: everything is inert unless Sapph's Cooking (mod id SapphCooking_B42) is active AND its
IceCubes item script exists, so the option never shows and nothing is created without the mod.
The machine must be powered (its container's isPowered(), as vanilla's loot window checks fridges;
falls back to the square's electricity / hydro power for the plain machine). Only machines built
with Knox (modData.KBW.buildableId), not the TK pack's map-placed ones.

Two files, written into the Community submod (and the test bundle):
  media/lua/shared/TimedActions/KBWCommunityMakeIceAction.lua  B42 timed action; complete() runs on
                                                               the server in MP and adds the items
  media/lua/client/KBWCommunity_IceMachineMenu.lua             the right-click option
Kahlua-safe: no next, goto, integer division or bitwise operators.
"""
import os

ACTION_LUA = "KBWCommunityMakeIceAction.lua"
MENU_LUA = "KBWCommunity_IceMachineMenu.lua"
ICE_MACHINES = ["community.tk.kitchen_misc.ice_machine", "community.tk.kitchen_misc.ice_machine_65",
                "community.tk.kitchen_misc.ice_machine_100"]
SAPPH_MOD = "SapphCooking_B42"
ICE_ITEM = "SapphCooking.IceCubes"
ICE_PER_USE = 2
DURATION = 100          # same as vanilla's glass removal
SOUND = "IceBreaking"   # Sapph's own sound for its ice recipe (SapphCooking_sounds.txt)

_COMMON = r'''
KBWCommunityIce = KBWCommunityIce or {}
local I = KBWCommunityIce
I.ITEM = "%(item)s"
I.PER_USE = %(per_use)d
I.SOUND = "%(sound)s"
I.MACHINES = {
%(machines)s
}

-- Sapph's Cooking active and its ice item defined
function I.available()
    if type(getActivatedMods) ~= "function" then return false end
    local mods = getActivatedMods()
    if not mods or type(mods.contains) ~= "function" or not mods:contains("%(mod)s") then return false end
    local sm = getScriptManager and getScriptManager()
    return sm ~= nil and sm:FindItem(I.ITEM) ~= nil
end

-- one of our ice machines, built with Knox Buildworks
function I.isMachine(obj)
    if not obj or not obj.hasModData or not obj:hasModData() then return false end
    local md = obj:getModData().KBW
    return type(md) == "table" and I.MACHINES[md.buildableId] == true
end

function I.isPowered(obj)
    local c = obj.getContainer and obj:getContainer()
    if c and c.isPowered and c:isPowered() then return true end
    local sq = obj:getSquare()
    if not sq then return false end
    if sq.haveElectricity and sq:haveElectricity() then return true end
    local world = getWorld and getWorld()
    return world ~= nil and world.isHydroPowerOn and world:isHydroPowerOn() and not sq:isOutside()
end
'''

_ACTION = r'''-- AUTO-GENERATED by pz_craft_loops/ice_machine_ice.py -- do not edit by hand.
-- "Make Ice" at one of our ice machines: Sapph's Cooking ice cubes. Inert without Sapph's Cooking.
-- Kahlua-safe: no next, goto, integer division or bitwise operators.
require "TimedActions/ISBaseTimedAction"
%(common)s
KBWCommunityMakeIceAction = ISBaseTimedAction:derive("KBWCommunityMakeIceAction")
local A = KBWCommunityMakeIceAction

function A:isValid()
    return I.available() and self.machine ~= nil and self.machine:getObjectIndex() ~= -1
        and I.isMachine(self.machine) and I.isPowered(self.machine)
end

function A:waitToStart()
    self.character:faceThisObject(self.machine)
    return self.character:shouldBeTurning()
end

function A:update()
    self.character:faceThisObject(self.machine)
    self.character:setMetabolicTarget(Metabolics.LightWork)
end

function A:start()
    -- (user, in game 2026-11-18: no sound heard; the log showed the character's emitter returning 0 for
    -- Sapph's sound) the character's emitter first, as vanilla actions do; if it gives no handle, the
    -- machine's square plays it (confirmed audible in game)
    self.sound = self.character:playSound(I.SOUND)
    if not self.sound or self.sound == 0 then
        local sq = self.machine and self.machine:getSquare()
        if sq and sq.playSound then sq:playSound(I.SOUND) end
    end
    self:setActionAnim("Loot")
    self.character:SetVariable("LootPosition", "Mid")
    self:setOverrideHandModels(nil, nil)
end

function A:stopIceSound()
    if self.sound and self.sound ~= 0 then self.character:stopOrTriggerSound(self.sound) end
end

function A:stop()
    self:stopIceSound()
    ISBaseTimedAction.stop(self)
end

-- the 3 s clip is left to finish (also with instant timed actions); only a cancel cuts it
function A:perform()
    ISBaseTimedAction.perform(self)
end

-- runs on the server in multiplayer (and in single player): re-checks, then adds the cubes
function A:complete()
    if not (I.available() and self.machine and self.machine:getObjectIndex() ~= -1
            and I.isMachine(self.machine) and I.isPowered(self.machine)) then
        return false
    end
    local inv = self.character:getInventory()
    for _ = 1, I.PER_USE do
        local item = inv:AddItem(I.ITEM)
        if item then sendAddItemToContainer(inv, item) end
    end
    return true
end

function A:getDuration()
    if self.character:isTimedActionInstant() then return 1 end
    return %(duration)d
end

function A:new(character, machine)
    local o = ISBaseTimedAction.new(self, character)
    o.machine = machine
    o.maxTime = o:getDuration()
    return o
end
'''

_MENU = r'''-- AUTO-GENERATED by pz_craft_loops/ice_machine_ice.py -- do not edit by hand.
-- Right-click one of our ice machines (built with Knox Buildworks) -> "Make Ice". Shown only when
-- Sapph's Cooking is active. Kahlua-safe: no next, goto, integer division or bitwise operators.
require "TimedActions/ISTimedActionQueue"
require "TimedActions/KBWCommunityMakeIceAction"

local function onMakeIce(playerObj, machine)
    local sq = machine:getSquare()
    if not sq then return end
    if luautils.walkAdj(playerObj, sq, true) then
        ISTimedActionQueue.add(KBWCommunityMakeIceAction:new(playerObj, machine))
    end
end

local function onFill(playerNum, context, worldObjects, test)
    if test or not KBWCommunityIce or not KBWCommunityIce.available() then return end
    local I = KBWCommunityIce
    local playerObj = getSpecificPlayer(playerNum)
    if not playerObj then return end
    local seen = {}
    for i = 1, #worldObjects do
        local sq = worldObjects[i] and worldObjects[i]:getSquare()
        if sq and not seen[sq] then
            seen[sq] = true
            local objects = sq:getObjects()
            for j = 0, objects:size() - 1 do
                local obj = objects:get(j)
                if I.isMachine(obj) then
                    local label = getTextOrNull("ContextMenu_KBWCB_MakeIce") or "Make Ice"
                    local option = context:addOption(label, playerObj, onMakeIce, obj)
                    if not I.isPowered(obj) then
                        option.notAvailable = true
                        local tip = ISWorldObjectContextMenu.addToolTip()
                        tip.description = getTextOrNull("Tooltip_KBWCB_MakeIceNoPower") or "The ice machine needs power."
                        option.toolTip = tip
                    end
                    return
                end
            end
        end
    end
end

Events.OnFillWorldObjectContextMenu.Add(onFill)
'''


def _check(name, text):
    code = "\n".join(l.split("--", 1)[0] for l in text.splitlines())
    for bad in ("next(", "goto ", "//", "debug.", " & ", " | ", "<<", ">>"):
        if bad in code.replace("~=", ""):
            raise RuntimeError("Kahlua-unsafe construct in %s: %r" % (name, bad))


def write_ice_lua(media_dir):
    """Write both files under media_dir (…/42/media). Returns the two paths."""
    common = _COMMON % {"item": ICE_ITEM, "per_use": ICE_PER_USE, "sound": SOUND, "mod": SAPPH_MOD,
                        "machines": "\n".join('    ["%s"] = true,' % m for m in ICE_MACHINES)}
    action = _ACTION % {"common": common, "duration": DURATION}
    menu = _MENU
    out = []
    for rel, text, name in ((os.path.join("lua", "shared", "TimedActions", ACTION_LUA), action, ACTION_LUA),
                            (os.path.join("lua", "client", MENU_LUA), menu, MENU_LUA)):
        _check(name, text)
        p = os.path.join(media_dir, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w", encoding="utf-8", newline="\n").write(text)
        out.append(p)
    return out
