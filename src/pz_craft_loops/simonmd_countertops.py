# KBW face -> straight shape offset (KBW faces are the opposite of the tile Facing: W = Facing E, ...)
FACE_SHAPE = {"W": sdf.CT_SHAPES["E"]["straight"], "N": sdf.CT_SHAPES["S"]["straight"],
              "E": sdf.CT_SHAPES["W"]["straight"], "S": sdf.CT_SHAPES["N"]["straight"]}


def _copy(colour_src, shape):
    return sdf.copy_name(sdf.CT_SHEET, colour_src + shape)


def build():
    out = []
    for level, (slug, name, src) in enumerate(sdf.CT_COLOURS, 1):
        faces = {f: {"layers": [{"rows": [[_copy(src, s)]]}]} for f, s in FACE_SHAPE.items()}
        out.append({
            "id": PREFIX + slug, "allowSpriteReuse": True,
            "translationKey": "IGUI_WESimon_countertop_" + slug, "displayName": "%s Counter Top" % name,
            "category": "Containers", "subcategory": "Counter Tops", "material": "Stone", "materialTags": ["Stone"],
            "iconSprite": _copy(src, FACE_SHAPE["W"]),
            "placement": {"kind": "object", "requiresFloor": True},
            "tags": ["simonmd", "ravencreek", "world-essentials", "counter-top"],
            "stages": [{"id": "built", "geometry": {"faces": faces}, "requirements": COST,
                        "construction": CONSTRUCTION,
                        "object": {"isThumpable": False, "dismantable": False, "canPassThrough": True,
                                   "blockAllSquare": False},
                        "callbacks": {"onIsValid": LUA_GLOBAL + ".OnIsValid", "onCreate": LUA_GLOBAL + ".OnCreate"}}],
            "group": {"id": PREFIX + "marble", "name": "Marble Counter Tops",
                      "translationKey": "IGUI_WESimon_countertop_group", "level": level},
        })
    return out


_LUA = r'''-- AUTO-GENERATED by pz_craft_loops/simonmd_countertops.py -- do not edit by hand.
-- Marble counter tops (Raven Creek Buildworks). The built piece is a placeholder: OnCreate attaches the
-- top to the counter as its FIRST attached sprite (how vanilla draws counter overlays), so it draws over
-- the counter and under anything on it (a sink), then removes the placeholder. Tracked in KBW's
-- modData.KBWAttachedSprites, so KBW's "Remove ..." context option takes it off again.
-- Kahlua-safe: no next, goto, integer division or bitwise operators.
%(G)s = %(G)s or {}
local G = %(G)s

local PREFIX = "%(tileset)s_"
local FIRST, LAST = %(first)d, %(last)d
local SHAPES = {%(shapes)s}
local FACE_FACING = { w = "E", n = "S", e = "W", s = "N" }

-- copy index of one of our counter tops, else nil
local function topIndex(name)
    if type(name) ~= "string" or string.sub(name, 1, string.len(PREFIX)) ~= PREFIX then return nil end
    local n = tonumber(string.sub(name, string.len(PREFIX) + 1))
    if n and n >= FIRST and n <= LAST then return n end
    return nil
end
G.topIndex = topIndex

local function isCounter(object)
    local sprite = object and object:getSprite() or nil
    if not sprite or topIndex(sprite:getName()) then return false end
    local props = sprite:getProperties()
    return props ~= nil and props:has("container") and props:get("container") == "counter"
end

-- the counter on a square (the first one in the object list)
local function findCounter(square)
    if not square then return nil end
    local objects = square:getObjects()
    for i = 0, objects:size() - 1 do
        local object = objects:get(i)
        if isCounter(object) then return object end
    end
    return nil
end
G.findCounter = findCounter

-- shape offset (0-7) for a counter: its own Facing / corner group, else the player's rotation
local function shapeFor(counter, face)
    local props = counter:getSprite():getProperties()
    local facing = props:has("Facing") and props:get("Facing") or nil
    local shapes = facing and SHAPES[facing] or nil
    if shapes then
        local group = props:has("GroupName") and props:get("GroupName") or ""
        if string.find(group, "Corner", 1, true) then return shapes.corner end
        return shapes.straight
    end
    shapes = SHAPES[FACE_FACING[face or ""] or "E"]
    return shapes.straight
end
G.shapeFor = shapeFor

function G.OnIsValid(params)
    return findCounter(params and params.square) ~= nil
end

function G.OnCreate(params)
    local part = params and params.thumpable or nil
    local square = part and part:getSquare() or nil
    local sprite = part and part:getSprite() or nil
    local n = sprite and topIndex(sprite:getName()) or nil
    local counter = findCounter(square)
    -- no counter any more: keep the placeholder (better than losing the materials)
    if not n or not counter then return nil end
    local name = PREFIX .. tostring(FIRST + math.floor((n - FIRST) / 8) * 8 + shapeFor(counter, params.facing))
    local top = getSprite(name)
    if not top then return nil end
    -- our top goes first; any other attached sprite (vanilla stains etc.) stays above it
    local list = ArrayList.new()
    list:add(top:newInstance())
    local old = counter:getAttachedAnimSprite()
    if old then
        for i = 0, old:size() - 1 do
            local instance = old:get(i)
            local parent = instance and instance:getParentSprite() or nil
            if not (parent and topIndex(parent:getName())) then list:add(instance) end
        end
    end
    counter:setAttachedAnimSprite(list)
    local data = counter:getModData()
    local tracked = {}
    for _, entry in ipairs(data.KBWAttachedSprites or {}) do
        if not topIndex(entry.sprite) then tracked[#tracked + 1] = entry end
    end
    tracked[#tracked + 1] = { sprite = name, buildableId = params.buildableId }
    data.KBWAttachedSprites = tracked
    -- the placeholder was only added on the server; clients never saw it
    square:RemoveTileObject(part)
    if isServer() then
        counter:transmitUpdatedSpriteToClients()
        counter:transmitModData()
    end
    return { objectAlreadyTransmitted = true }
end
'''


def write_lua(dest_path):
    shapes = ", ".join('%s = { straight = %d, corner = %d }' % (f, v["straight"], v["corner"])
                       for f, v in sorted(sdf.CT_SHAPES.items()))
    first = sdf.CT_FIRST_COPY
    last = first + 8 * len(sdf.CT_COLOURS) - 1
    assert sdf.copy_name(sdf.CT_SHEET, sdf.CT_FIRST_SRC) == "%s_%d" % (sdf.COPY_TILESET, first)
    lua = _LUA % {"G": LUA_GLOBAL, "tileset": sdf.COPY_TILESET, "first": first, "last": last, "shapes": " " + shapes + " "}
    for bad in ("next(", "goto ", "//", "<<", ">>"):
        assert bad not in lua.replace("-- Kahlua-safe: no next, goto, integer division or bitwise operators.", ""), bad
    os.makedirs(os.path.dirname(dest_path), exist_ok=True)
    open(dest_path, "w", encoding="utf-8", newline="\n").write(lua)


def main():
    out = build()
    ids = [b["id"] for b in out]
    assert len(ids) == len(set(ids))
    doc = {"schemaVersion": 1, "category": "Containers",
           "source": ("Simon MD marble counter tops (overlays_Simon_MD 56-87, art from Raven Creek's LCB42_SimonMDsTiles "
                      "pack, on our KBWRavenCreek copies): built onto an existing counter as an attached sprite "
                      "(KBWRavenCreek_CounterTops.lua). Costs first pass. Generated by "
                      "pz_craft_loops/simonmd_countertops.py."),
           "buildables": out}
    json.dump(doc, open(OUT, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("wrote %s (%d buildables)" % (OUT, len(ids)))


if __name__ == "__main__":
    main()
