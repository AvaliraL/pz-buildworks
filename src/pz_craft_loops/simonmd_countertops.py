"""Marble counter tops (user, 2026-11-17) for "World Essentials - Raven Creek Buildworks" (gated on
RavenCreek_B42): zomboid/simonmd/05_simonmd_countertops.json + KBWRavenCreek_CounterTops.lua.

Art: Simon MD's overlays_Simon_MD 56-87 (Dark / White / Gold / Blue Marble Counter Top, 8 shapes each:
4 straight, 4 corner). The standalone Simon MD pack flags them TileOverlay; Raven Creek ships the art but
no tiledef for that sheet, so they are built on our copies (simonmd_doors_furniture.COPIES 28-59).

Draw order (user: above the counter, below anything on it, such as a sink). This is how vanilla draws
its own counter overlays (CounterOverlays.lua -> TileOverlays.updateTileOverlaySprite, read from
projectzomboid.jar): the overlay is an attached sprite of the counter object, inserted FIRST in its
attachedAnimSprite list, and its depth is the counter's (tileDepthTextureAssignments). An attached
sprite draws straight after its object, so it covers the counter and every later object on the square
(sink, appliance, clutter) draws over it. A separate object would draw in square-list order, so a top
built after the sink would cover it.

So the buildable is a placeholder: the player places the piece on a counter square (onIsValid needs a
counter there), and onCreate (server side, as vanilla's barricade OnCreate) attaches the top to the
counter, removes the placeholder before clients ever see it, and returns objectAlreadyTransmitted.
The shape is picked from the counter's own tile (Facing + "Corner" in GroupName, vanilla counters and
anything that copies their properties); the player's rotation is only the fallback. Building a second
top on the same counter replaces the first. The top is tracked in KBW's own modData.KBWAttachedSprites,
so KBW's context menu offers "Remove <name>" (no refund, as for KBW's wall details).
Costs are our first pass (masonry: 2 stone blocks + concrete, trowel). NOT yet tested in game.
"""
