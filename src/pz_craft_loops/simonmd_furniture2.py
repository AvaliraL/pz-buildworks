# timed actions KBW accepts in our shipped definitions (a wrong one silently drops the buildable in game)
KNOWN_ACTIONS = {"BuildWallHammer", "BuildWallMetal", "BuildWallNoTool", "BuildWoodenStructureMedium",
                 "BuildWoodenStructureSmall", "BuildMetalStructureMedium", "BuildLowMetal", "BuildLowNoTool",
                 "BuildLowHammer"}


def _write(path, category, source, buildables):
    ids = [b["id"] for b in buildables]
    assert len(ids) == len(set(ids)), ids
    for b in buildables:
        for st in b["stages"]:
            act = (st.get("construction") or {}).get("timedAction")
            assert act in KNOWN_ACTIONS, (b["id"], act)
    json.dump({"schemaVersion": 1, "category": category, "source": source, "buildables": buildables},
              open(path, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("wrote %s (%d buildables)" % (path, len(ids)))


