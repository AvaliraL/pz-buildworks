def neon_link_groups():
    """{sprite name: run key} for the neon strip copies: colour + height (cyan / pink, high / low)."""
    out = {}
    for c, (sh, n) in sorted(sdf.COPIES.items()):
        if sh == sdf.NEON_SHEET and n in sdf.NEON_STRIPS:
            _wall, rgb = sdf.neon_role(n)
            colour = sdf.NEON_COLOR_COPIES[c][1] if c in sdf.NEON_COLOR_COPIES else (
                "cyan" if rgb == sdf.NEON_CYAN else "pink")
            out["%s_%d" % (sdf.COPY_TILESET, c)] = "%s_%s" % (colour, "high" if n < 26 else "low")
    return out


def write_neon_link_lua(dest_path):
    rows = "\n".join('    ["%s"] = "%s",' % (k, v) for k, v in sorted(neon_link_groups().items()))
    lua = _NEON_LINK_LUA % rows
    for bad in ("next(", "goto ", "<<", ">>", "//"):
        assert bad not in lua, bad
    os.makedirs(os.path.dirname(dest_path), exist_ok=True)
    open(dest_path, "w", encoding="utf-8", newline="\n").write(lua)


