def _piece(slug, name, cat, sub, faces, req, con, obj, placement=FLOOR, container=None, tags=(), group=None,
           level=None, callbacks=None, material="Wood", icon=None):
    st = {"id": "built", "geometry": {"faces": faces}, "requirements": copy.deepcopy(req),
          "construction": copy.deepcopy(con), "object": dict(obj)}
    if container:
        st["container"] = dict(container)
    if callbacks:
        st["callbacks"] = dict(callbacks)
    b = {"id": PREFIX + slug, "allowSpriteReuse": True, "translationKey": "IGUI_WESimon_" + slug,
         "displayName": name, "category": cat, "subcategory": sub, "material": material,
         "materialTags": [material], "iconSprite": icon or faces.get("W", faces.get("N"))["layers"][0]["rows"][0][0],
         "placement": dict(placement), "tags": TAGS + list(tags), "stages": [st]}
    if group:
        b["group"] = {"id": PREFIX + group[0], "name": group[1],
                      "translationKey": "IGUI_WESimon_%s_group" % group[0], "level": level}
    return b


