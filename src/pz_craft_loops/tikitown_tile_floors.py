# -*- coding: utf-8 -*-
"""Generate 50_tikitown_tile_floors.json (user, 2026-11-14): the six floors_interior_tilesandwood_tterika_01
tile floors that World Essentials' Knox Buildworks Expansion (20_tikitown.json) does not build.

Found through the BuildingCraft "Erika's tiles" addon (buildingcraft_b42_inventory.py): Drazion's
*_tterika_* sheets are copies of Erika's tiles at the same indices, and the addon builds these six
as floors. Checked here: each tile is a pack FloorTile with solidfloor (tile flags read below).

   4 Blue Diagonal Tiles     5 Red Diagonal Tiles     6 Orange Diagonal Tiles
  11 Blue Tiles             13 Dark Blue Tiles        14 Red Tiles
(13 is a darker blue than 11; the pack names both "Blue Tiles", so 13 is renamed.)

Each piece is a copy of WE's own buildable for the nearest sibling on the sheet (7 Beige Diagonal
Tiles for the diagonals, 12 Pink Tiles for the plain tiles): same placement, cost (mason's trowel,
1 concrete use, 2 clay tiles, Masonry 1), construction and subcategory, so they sit with WE's
floors in the menu. BuildingCraft's own cost for these (1 plank + 1 nails, Woodwork 4) is not used:
it does not fit ceramic tiles and would differ from the 60+ WE floors on the same sheet.
NOT yet tested in game.
"""
import copy
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kbw_tilepatch as k   # noqa: E402

SHEET = "floors_interior_tilesandwood_tterika_01"
OUT = r"c:\Users\josep\Kiro\zomboid\tikitown\50_tikitown_tile_floors.json"
WE_DEFS = (r"C:\Program Files (x86)\Steam\steamapps\workshop\content\108600\3733324672\mods"
           r"\World Essentials - Knox Buildworks Expansion\42\media\KnoxBuildworks\definitions\20_tikitown.json")
# tile index -> (display name, WE sibling tile used as the template)
FLOORS = {
    4: ("Blue Diagonal Tiles", 7),
    5: ("Red Diagonal Tiles", 7),
    6: ("Orange Diagonal Tiles", 7),
    11: ("Blue Tiles", 12),
    13: ("Dark Blue Tiles", 12),
    14: ("Red Tiles", 12),
}


def _spr(i):
    return "%s_%d" % (SHEET, i)


def _we_by_tile():
    d = json.load(open(WE_DEFS, encoding="utf-8-sig"))
    out = {}
    for b in d["buildables"]:
        faces = b["stages"][0]["geometry"]["faces"]
        if list(faces) == ["W"]:
            s = faces["W"]["layers"][0]["rows"][0][0]
            if s.startswith(SHEET + "_"):
                out[int(s.rsplit("_", 1)[1])] = b
    return out


def build():
    we = _we_by_tile()
    clash = sorted(set(FLOORS) & set(we))
    if clash:
        raise RuntimeError("WE already builds %s" % [_spr(i) for i in clash])
    _v, ts, _o = k._parse(open(k._TIKITOWN_TILES, "rb").read())
    tiles = ts[SHEET.encode()][6]
    out = []
    for i, (name, tmpl_i) in sorted(FLOORS.items()):
        p = dict(tiles[i])
        if p.get(b"MoveType") != b"FloorTile" or b"solidfloor" not in p:
            raise RuntimeError("%s is not a floor tile: %s" % (_spr(i), p))
        b = copy.deepcopy(we[tmpl_i])
        b.pop("group", None)                       # WE gives each floor its own one-piece card
        b["id"] = "worldessentials.tikitown.%s_%d" % (SHEET, i)
        b["displayName"] = name
        b["translationKey"] = "IGUI_WETiki_%s_%d" % (SHEET, i)
        b["tooltipKey"] = "Tooltip_KBW_Shared_Floor"
        b["iconSprite"] = _spr(i)
        b["stages"][0]["geometry"] = {"faces": {"W": {"layers": [{"rows": [[_spr(i)]]}]}}}
        b.setdefault("tags", ["tikitown", "drazion", "world-essentials"])
        out.append(b)
    return out


def main():
    out = build()
    doc = {
        "schemaVersion": 1,
        "category": "Floors",
        "source": ("TikiTown floors_interior_tilesandwood_tterika_01 (Drazion's Tilepack): the six tile floors "
                   "WE's 20_tikitown.json does not build, on WE's own floor setup. Generated by "
                   "pz_craft_loops/tikitown_tile_floors.py."),
        "buildables": out,
    }
    ids = [b["id"] for b in out]
    assert len(ids) == len(set(ids))
    json.dump(doc, open(OUT, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print("wrote %s (%d buildables)" % (OUT, len(ids)))


if __name__ == "__main__":
    main()
