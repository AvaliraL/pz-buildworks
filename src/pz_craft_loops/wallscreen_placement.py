# -*- coding: utf-8 -*-
"""Wall Screen TV placement next to counters and upper cabinets (user, 2026-11-19, on the server: "the wall screen
tv cannot be placed against the wall if the tile has a counter or upper counter. and the TV itself appears to block
placement of both, but not construction").

Cause: vanilla's moveable Place check (ISMoveableSpriteProps:canPlaceMoveableInternal) only knows two heights on a
wall. A WallObject marked IsHigh (our Wall Screen) may not share a square with another IsHigh WallObject of the
same Facing (every upper cabinet on that wall), and nothing on the floor of a square holding an IsHigh object may
be placed unless it is IsLow; same-facing WallObjects with neither flag block everything. Knox Buildworks builds
with its own rules (a high wall object passes over counters), so building worked and placing did not.

Fix, our Lua only, our Wall Screen sprites only (Community submod + test bundle; shared, so the server check
agrees): canPlaceMoveableInternal is wrapped once. Vanilla's answer is kept whenever it says yes. When it says no:
  * placing a Wall Screen: allowed when vanilla's own wall test passes (getWallForFacing) and the square has no
    other Wall Screen and no same-facing mid-height wall object (a WallObject with neither IsHigh nor IsLow:
    mirrors, wall cabinets). Counters, upper cabinets and anything else in the square are ignored, as Knox does.
  * placing anything else on a square that holds a Wall Screen: vanilla's rule is re-run with the Wall Screen
    left out (WallObject: the same-facing loop; floor Object: isFreeTile + the IsHigh / IsLow pairing).
Everything else is vanilla. Kahlua-safe: no next, goto, integer division or bitwise operators.
"""
import os

LUA_NAME = "KBWCommunity_WallScreenPlacement.lua"
# IceShell 176 / 177 = the first Wall Screen copies (placed TVs keep them), 205 / 206 = the current ones
SPRITES = ["KBWCommunityIceShell_176", "KBWCommunityIceShell_177", "KBWCommunityIceShell_205",
           "KBWCommunityIceShell_206"]

LUA = r'''-- AUTO-GENERATED by pz_craft_loops/wallscreen_placement.py -- do not edit by hand.
-- The Wall Screen TV and counters / upper cabinets can be PLACED (moveable Place) on the same square, as Knox
-- Buildworks already lets them be built. Vanilla's answer is kept whenever it allows a placement; only a "no" that
-- comes from a Wall Screen is re-checked. Kahlua-safe: no next, goto, integer division or bitwise operators.
require "Moveables/ISMoveableSpriteProps"

KBWCommunityWallScreen = KBWCommunityWallScreen or {}
local W = KBWCommunityWallScreen
W.SPRITES = {
%(sprites)s
}

local function propsOf(obj)
    local sp = obj and obj:getSprite()
    return sp and sp:getProperties() or nil, sp and sp:getName() or nil
end

local function isScreen(obj)
    local _p, name = propsOf(obj)
    return name ~= nil and W.SPRITES[name] == true
end

function W.squareHasScreen(square)
    local objs = square:getObjects()
    for i = 0, objs:size() - 1 do
        if isScreen(objs:get(i)) then return true end
    end
    return false
end

-- placing a Wall Screen: the wall must be there (vanilla's test); only another screen or a same-facing
-- mid-height wall object (neither IsHigh nor IsLow) blocks it
function W.screenCanPlace(self, square)
    if not (self.facing and self:getWallForFacing(square, self.facing)) then return false end
    local objs = square:getObjects()
    for i = 0, objs:size() - 1 do
        local obj = objs:get(i)
        local p = propsOf(obj)
        if p and p:has("Facing") and p:get("Facing") == self.facing then
            if isScreen(obj) then return false end
            if p:has("MoveType") and p:get("MoveType") == "WallObject" and not p:has("IsHigh") and not p:has("IsLow") then
                return false
            end
        end
    end
    return true
end

-- vanilla's WallObject loop for the piece being placed, with Wall Screens left out
local function wallObjectFits(self, square)
    local wall
    if self.allowDoorFrame then
        wall = self.facing and self:getWallForFacing(square, self.facing, "WallAndDoor")
    else
        wall = self.facing and self:getWallForFacing(square, self.facing)
    end
    if not wall then return false end
    local objs = square:getObjects()
    for i = 0, objs:size() - 1 do
        local obj = objs:get(i)
        if not isScreen(obj) then
            local p = propsOf(obj)
            if p then
                local high, low = p:has("IsHigh"), p:has("IsLow")
                if p:has("MoveType") and p:get("MoveType") == "WallObject" then
                    if p:has("Facing") and p:get("Facing") == self.facing then
                        if (not high and not low) or (high and self.isHigh) or (low and self.isLow) then return false end
                    end
                elseif p:has("BlocksPlacement") then
                    if (not high and not low) or (high and self.isHigh) or (low and self.isLow) then return false end
                end
            end
        end
    end
    return true
end

-- vanilla's free-standing Object rule (not table-top) with Wall Screens left out of the IsHigh / IsLow pairing
local function floorObjectFits(self, square)
    if not self:isFreeTile(square) then return false end
    local high, low = false, false
    local objs = square:getObjects()
    for i = 0, objs:size() - 1 do
        local obj = objs:get(i)
        if not isScreen(obj) then
            local p = propsOf(obj)
            if p then
                if p:has("IsHigh") then high = true end
                if p:has("IsLow") and not p:has(IsoFlagType.canBeRemoved) then low = true end
            end
        end
    end
    local ok = true
    if high then ok = self.isLow == true end
    if low then ok = self.isHigh == true end
    if ok and self.isSquareAtTopOfStairs and self:isSquareAtTopOfStairs(square) then ok = false end
    return ok
end

function W.relaxed(self, square, forceTypeObject)
    if not square or not self.isMoveable then return false end
    if square.isVehicleIntersecting and square:isVehicleIntersecting() then return false end
    if not square:getFloor() then return false end
    if self.spriteName and W.SPRITES[self.spriteName] then
        return W.screenCanPlace(self, square)
    end
    if not W.squareHasScreen(square) then return false end
    if self.type == "WallObject" and not forceTypeObject then
        return wallObjectFits(self, square)
    end
    if (self.type == "Object" or forceTypeObject) and not self.isTableTop and not self.fitsBeneathCountertop then
        return floorObjectFits(self, square)
    end
    return false
end

local function install()
    if not ISMoveableSpriteProps or ISMoveableSpriteProps.__kbwWallScreenPlace then return end
    local orig = ISMoveableSpriteProps.canPlaceMoveableInternal
    if type(orig) ~= "function" then return end
    ISMoveableSpriteProps.canPlaceMoveableInternal = function(self, character, square, item, forceTypeObject)
        local ok = orig(self, character, square, item, forceTypeObject)
        if ok then return ok end
        local good, res = pcall(W.relaxed, self, square, forceTypeObject)
        if good and res == true then return true end
        return ok
    end
    ISMoveableSpriteProps.__kbwWallScreenPlace = true
end

install()
'''


def _check(text):
    code = "\n".join(l.split("--", 1)[0] for l in text.splitlines())
    for bad in ("next(", "goto ", "//", "debug.", " & ", " | ", "<<", ">>"):
        if bad in code.replace("~=", ""):
            raise RuntimeError("Kahlua-unsafe construct in %s: %r" % (LUA_NAME, bad))


def lua():
    t = LUA % {"sprites": "\n".join('    ["%s"] = true,' % s for s in SPRITES)}
    _check(t)
    return t


def write_lua(media_dir):
    """Write the Lua under media_dir (.../42/media). Returns the path."""
    p = os.path.join(media_dir, "lua", "shared", LUA_NAME)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write(lua())
    return p
