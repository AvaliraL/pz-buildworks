def _same_json(a, b):
    """True when two .json files hold identical data (formatting-only differences ignored)."""
    import json
    try:
        return json.load(open(a, encoding="utf-8-sig")) == json.load(open(b, encoding="utf-8-sig"))
    except Exception:
        return False


def _sha(p):
    return hashlib.sha1(open(p, "rb").read()).hexdigest()


def _rel_files(root):
    out = {}
    for d, _, fs in os.walk(root):
        for f in fs:
            p = os.path.join(d, f)
            out[os.path.relpath(p, root)] = p
    return out


def sync_to_we_work(built_mod_root, submod, log_lines, extra_skip=()):
    """Copy built_mod_root/{42,common}/... into WORK/<submod>/ (same relative paths).
    Returns a dict of counts. Appends a readable report to log_lines."""
    dst_root = os.path.join(WORK, submod)
    up_root = os.path.join(UPSTREAM, submod)
    if not os.path.isdir(dst_root):
        raise RuntimeError("WE work copy missing: %s (run the snapshot step first)" % dst_root)
    skip = {s.lower() for s in ALWAYS_SKIP | WE_BASE_OWNED | WE_SUBMOD_OWNED | set(extra_skip)}
    built = _rel_files(built_mod_root)
    # GUARD (2026-10-31): WE now ships its own isolated copies of the Dylan sprites
    # (WECommunity_* tilesets, wecommunity_dylan.tiles / WECommunityDylan.pack, tiledef 8182) and
    # rewrote our definitions to use them. Syncing our builds (original Dylan sprite names) would
    # undo that, so refuse until our builder emits the same WECommunity_* names.
    up_dyl = os.path.join(up_root, "42", "media", "wecommunity_dylan.tiles")
    if os.path.isfile(up_dyl) and not any(os.path.basename(r).lower() == "wecommunity_dylan.tiles" for r in built):
        log_lines.append("   SYNC REFUSED: upstream uses WE's isolated WECommunity_* Dylan assets and our build "
                         "does not. Adopt them in the builder first (see OPEN_ISSUES.md, 2026-10-31).")
        return {"refused": 1}
    counts = {"new": 0, "changed": 0, "same": 0, "skipped_we_owned": 0}
    log_lines.append("== WE sync: %s -> %s" % (built_mod_root, dst_root))
    for rel, src in sorted(built.items()):
        name = os.path.basename(rel).lower()
        if name in skip:
            counts["skipped_we_owned"] += 1
            if name in WE_BASE_OWNED or name in WE_SUBMOD_OWNED:
                log_lines.append("   WE-OWNED (port by hand if changed): %s" % rel)
            continue
        dst = os.path.join(dst_root, rel)
        if os.path.isfile(dst) and (_sha(dst) == _sha(src)
                                    or (name.endswith(".json") and _same_json(dst, src))):
            counts["same"] += 1
            continue
        tag = "changed" if os.path.isfile(dst) else "new"
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        counts[tag] += 1
        log_lines.append("   %-7s %s" % (tag.upper(), rel))
    # files in the work copy that our build no longer produces (left in place, reported)
    work = _rel_files(dst_root)
    for rel in sorted(set(work) - set(built)):
        if os.path.basename(rel).lower() not in skip:
            log_lines.append("   STALE?  %s (in work copy, not in our build; left in place)" % rel)
    # how far work/ has drifted from upstream/
    drift = 0
    up = _rel_files(up_root) if os.path.isdir(up_root) else {}
    for rel, p in _rel_files(dst_root).items():
        if rel not in up or _sha(up[rel]) != _sha(p):
            drift += 1
    log_lines.append("   counts: %s; work files differing from upstream: %d" % (counts, drift))
    return counts
